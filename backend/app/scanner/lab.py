def run_patch_step(name: str, apk: Path, work_dir: Path, package: str | None) -> dict[str, Any]:
    """Execute a patch step only with explicit automation + invasive opt-in."""
    plan = build_patching_plan(apk, work_dir, package)
    step = next((s for s in plan["steps"] if s["name"] == name), None)
    if step is None:
        return {"status": "error", "detail": f"unknown patch workflow: {name}"}
    if not plan["executable"]:
        return {
            "status": "skipped", "detail": (
                "Invasive workflows require APKPT_TOOLCHAIN_AUTO=1 and APKPT_ALLOW_INVASIVE=1 "
                "plus an authenticated API call."
            ), "workflow": name,
        }
    if not step["available"] or not step["enabled"]:
        return {"status": "skipped", "detail": "tool unavailable or disabled", "workflow": name}
    if "manual" in str(step["status"]):
        return {"status": "skipped", "detail": "workflow requires manual interaction", "workflow": name}
    try:
        command = split_command(step["command"])
    except Exception as exc:
        return {"status": "error", "detail": f"invalid command: {exc}", "workflow": name}
    code, output = _run(command, timeout=config.TOOLCHAIN_TIMEOUT, cwd=work_dir)
    return {
        "status": "passed" if code == 0 else "error",
        "detail": f"exit {code}",
        "workflow": name,
        "command": step["command"],
        "output": output[-4000:],
    }


def build_lab_plan(
    apk: Path,
    work_dir: Path,
    package: str | None,
    network_config: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Generate emulator/proxy/CA commands and artifacts for an authorized lab."""
    lab_dir = work_dir / "lab"
    lab_dir.mkdir(parents=True, exist_ok=True)
    addon = lab_dir / "apkpt_mitm_addon.py"
    try:
        addon.write_text(MITM_ADDON, encoding="utf-8")
    except Exception:
        pass

    proxy = proxy_config()
    commands: list[dict[str, str]] = []
    if config.EMULATOR_CMD:
        commands.append({
            "name": "start_emulator",
            "command": _render(
                config.EMULATOR_CMD + (" -avd {avd}" if config.EMULATOR_AVD else "") + " -writable-system -no-snapshot",
                avd=config.EMULATOR_AVD, apk=str(apk), work=str(lab_dir),
            ),
        })
    listener_cmds = {
        "burp": f"{config.BURP_CMD} # configure Proxy listener on {proxy['host']}:{proxy['port']}",
        "zap": f"{config.ZAP_CMD} -daemon -host {proxy['host']} -port {proxy['port']} -config api.disablekey=true",
        "mitmproxy": f"{config.MITMPROXY_CMD} -l {proxy['host']}:{proxy['port']} -s {addon}",
    }
    if proxy["type"] in listener_cmds:
        commands.append({
            "name": f"start_{proxy['type']}",
            "command": listener_cmds[proxy["type"]],
        })
    commands.append({
        "name": "set_android_proxy",
        "command": f"{config.ADB_CMD} shell settings put global http_proxy {proxy['host']}:{proxy['port']}",
    })
    commands.append({
        "name": "clear_android_proxy",
        "command": f"{config.ADB_CMD} shell settings delete global http_proxy",
    })
    if config.CA_CERT_PATH:
        commands.append({
            "name": "push_proxy_ca",
            "command": f"{config.ADB_CMD} push {config.CA_CERT_PATH} /data/local/tmp/apkpt-proxy-ca.crt",
        })

    nsc = network_config or {}
    nsc_notes: list[str] = []
    if nsc.get("user_ca_trusted") is False:
        nsc_notes.append(
            "The declared Network Security Configuration does not trust user CAs on target SDK 24+. "
            "Use patch-apk.py or a test-only NSC override before expecting HTTPS interception to work."
        )
    if nsc.get("cleartext_enabled"):
        nsc_notes.append("Cleartext is permitted; confirm plaintext traffic with an interception proxy.")
    if nsc.get("pin_sets"):
        nsc_notes.append("Certificate pinning is declared; use Frida/objection only in the authorized lab.")

    return {
        "authorization": AUTHORIZATION_NOTICE,
        "status": "planned",
        "proxy": proxy,
        "emulator": emulator_status(),
        "commands": commands,
        "artifacts": {"mitm_addon": str(addon)},
        "ca_installation": {
            "configured": bool(config.CA_CERT_PATH),
            "path": config.CA_CERT_PATH or None,
            "steps": [
                "Push the CA to the test device only.",
                "For Android 7+ user CAs are not trusted by default; use a test-only NSC or a patched app.",
                "On Android 14+ the Conscrypt APEX CA store requires a rooted system-overlay workflow; "
                "perform it manually with APatch/Magisk only with written approval.",
                "Remove the CA and clear the proxy when the lab session ends.",
            ],
        },
        "network_security_notes": nsc_notes,
        "mobsf": {
            "url": config.MOBSF_URL or None,
            "dynamic_url": config.MOBSF_DYNAMIC_URL or None,
            "browser_open_enabled": config.BROWSER_OPEN_ENABLED,
        },
        "patching": build_patching_plan(apk, work_dir, package),
    }


def _valid_proxy_target(host: str, port: int) -> bool:
    if not host or len(host) > 253 or any(ch.isspace() for ch in host):
        return False
    if not all(ch.isalnum() or ch in ".-_" for ch in host):
        return False
    return 1 <= int(port) <= 65535


def apply_proxy(host: str, port: int, device_serial: str | None = None, clear: bool = False) -> dict[str, Any]:
    """Apply or clear the global HTTP proxy on an authorized test device."""
    if not config.EMULATOR_AUTO:
        return {
            "status": "skipped",
            "detail": "Set APKPT_EMULATOR_AUTO=1 to allow proxy changes on a connected test device.",
        }
    if not clear and not _valid_proxy_target(host, port):
        return {"status": "error", "detail": "invalid proxy host or port"}
    cmd = _adb_base(device_serial) + ["shell", "settings"]
    if clear:
        cmd += ["delete", "global", "http_proxy"]
    else:
        cmd += ["put", "global", "http_proxy", f"{host}:{int(port)}"]
    code, output = _run(cmd, timeout=30)
    return {
        "status": "applied" if code == 0 else "error",
        "detail": output[-1000:] or f"exit {code}",
        "command": " ".join(cmd),
        "proxy": None if clear else f"{host}:{int(port)}",
    }


def open_mobsf_browser(url: str | None = None, scan_id: str | None = None) -> dict[str, Any]:
    """Open an authorised MobSF UI in the configured/inbuilt Chromium browser."""
    base = config.MOBSF_URL or config.MOBSF_DYNAMIC_URL
    if not base:
        return {"status": "skipped", "detail": "MobSF URL is not configured (APKPT_MOBSF_URL)."}
    target = (url or base).strip()
    parsed = urlparse(target)
    if parsed.scheme not in ("http", "https") or not parsed.netloc:
        return {"status": "error", "detail": "only http(s) URLs are accepted"}
    base_parsed = urlparse(base)
    if (parsed.scheme, parsed.netloc) != (base_parsed.scheme, base_parsed.netloc):
        return {"status": "error", "detail": "URL must be within the configured MobSF instance"}
    base_path = base_parsed.path.rstrip("/")
    if base_path and not parsed.path.startswith(base_path + "/" if base_path != "/" else "/"):
        return {"status": "error", "detail": "URL must be within the configured MobSF instance"}
    if scan_id:
        separator = "&" if "?" in target else "?"
        target = f"{target}{separator}apkpt_scan={quote(str(scan_id), safe='')}"
    if not config.BROWSER_OPEN_ENABLED:
        return {
            "status": "skipped", "url": target,
            "detail": "Set APKPT_BROWSER_OPEN=1 to allow server-side browser launching.",
        }
    try:
        if config.CHROMIUM_CMD:
            parts = split_command(config.CHROMIUM_CMD)
            subprocess.Popen(parts + [target], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            return {"status": "launched", "url": target, "browser": config.CHROMIUM_CMD}
        if webbrowser.open(target):
            return {"status": "launched", "url": target, "browser": "system-default"}
        return {"status": "skipped", "url": target, "detail": "no browser could be launched"}
    except Exception as exc:
        return {"status": "error", "url": target, "detail": f"{type(exc).__name__}: {exc}"}
