"""Interception lab, emulator and APK-patching workflow planning.

This module deliberately separates *planning* from *execution*:

- Read-only probes and command generation always work.
- Applying a device proxy or opening a browser is an explicit API action.
- Root/system modification, Frida/objection injection, APK patching, modding and
  translation require both ``APKPT_TOOLCHAIN_AUTO=1`` and
  ``APKPT_ALLOW_INVASIVE=1`` and are never started by a normal scan.

All workflows are for authorized security testing only. A plan is evidence of
intent and prerequisites, not proof that a technique succeeded.
"""

from __future__ import annotations

import os
import shlex
import shutil
import subprocess
import webbrowser
from pathlib import Path
from typing import Any
from urllib.parse import quote, urlparse

from .. import config

AUTHORIZATION_NOTICE = (
    "For authorized security testing only. Use these workflows exclusively on devices, "
    "emulators and applications you own or have explicit written permission to test."
)

MITM_ADDON = r'''"""Optional mitmproxy addon generated by APK Pentest Platform.

Load with:  mitmdump -l 127.0.0.1:8080 -s apkpt_mitm_addon.py
Only metadata is logged. Do not persist patient payloads in shared artifacts.
"""

from mitmproxy import http

SENSITIVE_HINTS = ("/fhir", "/patient", "/observation", "/diagnosticreport", "/login", "/oauth", "/token")


def request(flow: http.HTTPFlow) -> None:
    url = flow.request.pretty_url
    if any(hint in url.lower() for hint in SENSITIVE_HINTS):
        print(f"[APKPT-MITM] {flow.request.method} {url}")
'''


def split_command(value: str) -> list[str]:
    """Split an env-provided command without mangling Windows paths."""
    return shlex.split(value or "", posix=(os.name != "nt"))


def _available(command: str) -> bool:
    parts = split_command(command)
    if not parts:
        return False
    if shutil.which(parts[0]):
        return True
    candidate = Path(parts[0])
    if candidate.exists():
        return True
    # Support "python patch-apk.py" style commands.
    for token in parts[1:]:
        if Path(token).suffix.lower() in (".py", ".jar", ".sh") and Path(token).exists():
            return True
    return False


def _run(cmd: list[str], timeout: int = 30, cwd: Path | None = None) -> tuple[int, str]:
    try:
        proc = subprocess.run(
            cmd, capture_output=True, text=True, timeout=timeout,
            errors="replace", cwd=str(cwd) if cwd else None,
        )
        return proc.returncode, ((proc.stdout or "") + (proc.stderr or "")).strip()
    except FileNotFoundError:
        return 127, "executable not found"
    except subprocess.TimeoutExpired:
        return 124, f"timed out after {timeout}s"
    except Exception as exc:
        return 1, str(exc)


def _render(template: str, **values: Any) -> str:
    out = str(template or "")
    for key, value in values.items():
        out = out.replace("{" + key + "}", str(value))
    return out


def _adb_base(serial: str | None = None) -> list[str]:
    cmd = split_command(config.ADB_CMD) or ["adb"]
    if serial or config.DAST_DEVICE_SERIAL:
        cmd += ["-s", serial or config.DAST_DEVICE_SERIAL]
    return cmd


def proxy_config() -> dict[str, Any]:
    """Normalise APKPT_DAST_PROXY into a usable interception profile."""
    raw = (config.DAST_PROXY or "").strip()
    if not raw:
        return {
            "configured": False, "type": "none", "host": config.PROXY_HOST,
            "port": config.PROXY_PORT, "endpoint": "",
        }

    lowered = raw.lower()
    proxy_type = "custom"
    if lowered in ("burp", "burpsuite"):
        proxy_type = "burp"
    elif lowered in ("zap", "owaspzap"):
        proxy_type = "zap"
    elif lowered in ("mitm", "mitmproxy", "mitmdump"):
        proxy_type = "mitmproxy"

    host, port = config.PROXY_HOST, config.PROXY_PORT
    if "://" in raw:
        parsed = urlparse(raw)
        host = parsed.hostname or host
        port = parsed.port or port
    else:
        value = raw
        if ":" in value:
            host, _, port_text = value.rpartition(":")
            if port_text.isdigit():
                port = int(port_text)
        elif proxy_type == "custom":
            host = value

    if proxy_type == "custom":
        lookup = f"{host}:{port}:{lowered}"
        if "8080" in lookup and ("burp" in lowered or host in ("burp", "burpsuite")):
            proxy_type = "burp"
        elif "8090" in lookup or "zap" in lowered:
            proxy_type = "zap"
        elif "8081" in lookup or "mitm" in lowered:
            proxy_type = "mitmproxy"

    return {
        "configured": True,
        "type": proxy_type,
        "host": host,
        "port": int(port),
        "endpoint": f"{host}:{int(port)}",
        "raw": raw,
    }


def emulator_status() -> dict[str, Any]:
    adb_parts = split_command(config.ADB_CMD) or ["adb"]
    adb_available = bool(shutil.which(adb_parts[0]) or Path(adb_parts[0]).exists())
    devices: list[str] = []
    if adb_available:
        code, out = _run(_adb_base() + ["devices"], timeout=15)
        if code == 0:
            for line in out.splitlines()[1:]:
                parts = line.split()
                if len(parts) >= 2 and parts[1] == "device":
                    devices.append(parts[0])
    return {
        "authorization": AUTHORIZATION_NOTICE,
        "adb_available": adb_available,
        "devices": devices,
        "emulator_available": _available(config.EMULATOR_CMD),
        "emulator_command": config.EMULATOR_CMD or None,
        "avd": config.EMULATOR_AVD or None,
        "emulator_auto": config.EMULATOR_AUTO,
        "invasive_allowed": config.ALLOW_INVASIVE,
        "proxy": proxy_config(),
        "ca_cert_configured": bool(config.CA_CERT_PATH),
        "mobsf_url": config.MOBSF_URL or None,
        "mobsf_dynamic_url": config.MOBSF_DYNAMIC_URL or None,
        "chromium_configured": bool(config.CHROMIUM_CMD),
        "browser_open_enabled": config.BROWSER_OPEN_ENABLED,
    }


